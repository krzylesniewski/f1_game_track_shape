# Rebuild the native Flutter path from the user-provided SVG (M, L, C, Z commands).
param([string]$Source = 'example/Circuit_Monza.svg')
[xml]$document = Get-Content -LiteralPath $Source -Raw -Encoding utf8
$node = $document.SelectSingleNode("//*[@id='path2241']")
if ($null -eq $node) { throw 'Missing path2241 in Monza SVG.' }
$pathData = $node.GetAttribute('d')
$tokens = [regex]::Matches($pathData, '[MLCZmlcz]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?') | ForEach-Object { $_.Value }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("// Generated by tool/import_monza.ps1 from example/Circuit_Monza.svg, path2241.")
$lines.Add("// Preserve the original cubic curves. No corner labels or background shapes.")
$lines.Add("import 'package:flutter/material.dart';")
$lines.Add('')
$lines.Add('Path monzaSvgPath() => Path()')
$index = 0
while ($index -lt $tokens.Count) {
  $command = $tokens[$index++]
  switch ($command) {
    'M' { $method = 'moveTo'; $count = 2 }
    'L' { $method = 'lineTo'; $count = 2 }
    'C' { $method = 'cubicTo'; $count = 6 }
    'z' { $lines.Add('  ..close();'); continue }
    default { throw "Unsupported SVG command: $command" }
  }
  if ($command -eq 'z') { continue }
  $arguments = $tokens[$index..($index + $count - 1)] -join ', '
  $index += $count
  $lines.Add("  ..$method($arguments)")
}
Set-Content -LiteralPath lib/game/monza_path.dart -Value $lines -Encoding utf8
$cleanSvg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600"><path id="monza" fill="none" stroke="currentColor" stroke-width="4" d="' + $pathData + '"/></svg>'
Set-Content -LiteralPath assets/tracks/monza.svg -Value $cleanSvg -Encoding utf8

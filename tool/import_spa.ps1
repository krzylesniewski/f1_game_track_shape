# Import the three colored sectors from the supplied map without approximating curves.
param([string]$Source = 'example/Spa-Francorchamps_of_Belgium.svg')
$ErrorActionPreference = 'Stop'
[xml]$document = Get-Content -LiteralPath $Source -Raw -Encoding utf8
$culture = [Globalization.CultureInfo]::InvariantCulture
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tool/import_spa.ps1 from the supplied Spa SVG.')
$lines.Add('// S1: path5814 (yellow); S2: path5818 (red); S3: path5820 (aqua).')
$lines.Add('// Retain cubic curves and the layer translation; omit all map labels.')
$lines.Add("import 'package:flutter/material.dart';")
$cleanPaths = [Collections.Generic.List[string]]::new()
$sector = 0
foreach ($id in @('path5814', 'path5818', 'path5820')) {
  $sector++
  $node = $document.SelectSingleNode("//*[@id='$id']")
  if ($null -eq $node) { throw "Missing sector path $id." }
  $translation = $node.ParentNode.GetAttribute('transform')
  if ($translation -notmatch '^translate\(([-\d.]+),([-\d.]+)\)$') {
    throw "Unsupported layer transform: $translation"
  }
  $translateX = [double]::Parse($Matches[1], $culture)
  $translateY = [double]::Parse($Matches[2], $culture)
  $pathData = $node.GetAttribute('d')
  $tokens = [regex]::Matches($pathData, '[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?') | ForEach-Object { $_.Value }
  $lines.Add('')
  $lines.Add("Path spaSector${sector}SvgPath() => Path()")
  $index = 0
  $command = ''
  $x = $translateX
  $y = $translateY
  while ($index -lt $tokens.Count) {
    if ($tokens[$index] -cmatch '^[A-Za-z]$') { $command = $tokens[$index++] }
    if ($command -cne 'm' -and $command -cne 'c') { throw "Unsupported SVG command $command" }
    $count = if ($command -ceq 'm') { 2 } else { 6 }
    $values = @()
    for ($j = 0; $j -lt $count; $j++) {
      $values += [double]::Parse($tokens[$index++], $culture)
    }
    $absolute = @()
    for ($j = 0; $j -lt $count; $j += 2) {
      $absolute += ($x + $values[$j]).ToString('0.########', $culture)
      $absolute += ($y + $values[$j + 1]).ToString('0.########', $culture)
    }
    $method = if ($command -ceq 'm') { 'moveTo' } else { 'cubicTo' }
    $lines.Add("  ..$method($($absolute -join ', '))")
    $x += $values[$count - 2]
    $y += $values[$count - 1]
  }
  $lines[$lines.Count - 1] += ';'
  $cleanPaths.Add('<path id="sector' + $sector + '" d="' + $pathData + '"/>')
}
Set-Content -LiteralPath lib/game/spa_path.dart -Value $lines -Encoding utf8
$cleanSvg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1415.7909 875.29749"><g transform="translate(2047.7528,-153.52072)" fill="none" stroke="currentColor" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">' + ($cleanPaths -join '') + '</g></svg>'
Set-Content -LiteralPath assets/tracks/spa.svg -Value $cleanSvg -Encoding utf8
